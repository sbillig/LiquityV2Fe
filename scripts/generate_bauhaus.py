#!/usr/bin/env python3
"""Translate the pinned Bauhaus geometry/color tables into Fe string templates.

Only the small expression vocabulary used by the reference geometry is accepted.
Generated output contains Fe runtime color selection, not sampled NFT outputs.
"""
import ast
from metadata_codegen import normalize_joins
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'reference/bold/contracts/src/NFTMetadata/utils/bauhaus.sol').read_text()
source = re.sub(r'//[^\n]*', '', source)
colors = dict(re.findall(r'string constant (\w+) = "([^"]+)";', source))
fields = ['rect1','rect2','rect3','rect4','rect5','poly','circle1','circle2','circle3']
functions = dict(re.findall(r'function (_(?:rects|polygons|circles)\d)\([^{}]+\{(.*?)\n    }', source, re.S))
literals = {}
def lit(s):
    if s not in literals:literals[s] = 'literal_' + str(len(literals))
    return literals[s] + '()'
def evaluate(expr):
    tokens = re.findall(r'"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|[\w.]+|[(),]', expr)
    pos = 0
    def parse():
        nonlocal pos
        t=tokens[pos];pos+=1
        if t.startswith(('"',"'")):return ast.literal_eval(t)
        if t in colors:return colors[t]
        if t.startswith('_colors.'):return '\x01'+t.split('.')[1]+'\x02'
        assert tokens[pos]=='(', (t,tokens[pos]);pos+=1
        args=[]
        if tokens[pos]!=')':
            while True:
                args.append(parse())
                if tokens[pos]!=',':break
                pos+=1
        assert tokens[pos]==')';pos+=1
        if t=='string.concat':return ''.join(args)
        if t=='_colorCode2Hex':return args[0]
        if t=='svg.prop':return args[0]+'="'+args[1]+'" '
        if t=='svg.path':return '<path d="'+args[0]+'" '+args[1]+'/>'
        assert t in ('svg.rect','svg.circle','svg.polygon'),t
        return '<'+t.split('.')[1]+' '+args[0]+'/>'
    result=parse();assert pos==len(tokens),(pos,tokens[pos:]);return result
out=['// SPDX-License-Identifier: MIT','// Generated by scripts/generate_bauhaus.py from the pinned reference.',
     'use std::abi::DynString','use std::evm::RawMem','use std::evm::packed::keccak_packed',
     'use super::metadata_string::{cat, text}']
for name,body in functions.items():
    expr=re.search(r'return (.*);',body,re.S).group(1)
    parts=re.split(r'\x01(\w+)\x02',evaluate(expr));args=[]
    for i,p in enumerate(parts):
        args.append((lit(p) if i%2==0 else f'color(colors[{fields.index(p)}])')+'.as_bytes()')
    out.append(f'fn {name[1:]}(_ colors: [u256; 9]) -> DynString uses (mem: mut RawMem) {{\n    join(('+', '.join(args)+'))\n}')
for index in range(1,4):
    body=re.search(r'function _colors'+str(index)+r'\([^{}]+\{(.*?)\n    }',source,re.S).group(1)
    rows=re.findall(r'return COLORS\((.*?)\);',body,re.S)
    assert len(rows)==4
    out.append(f'fn colors{index}(_ variant: u256) -> [u256; 9] {{')
    for n,row in enumerate(rows):
        codes=re.findall(r'colorCode\.(\w+)',row);assert len(codes)==9
        values=', '.join(str(list(colors).index(c)) for c in codes)
        out.append(('    if' if n==0 else '    else if' if n<3 else '    else')+(f' variant == {n}' if n<3 else '')+' { ['+values+'] }')
    out.append('}')
out.append('fn color(_ index: u256) -> DynString uses (mem: mut RawMem) {')
for i,value in enumerate(colors.values()):
    out.append(('    if' if i==0 else '    else if' if i<6 else '    else')+(f' index == {i}' if i<6 else '')+' { '+lit(value)+' }')
out.append('}')
out.append('''pub fn bauhaus(_ symbol: DynString, _ id: u256) -> DynString uses (mem: mut RawMem) {
    let hash = keccak_packed(symbol.as_bytes())
    let variant = id % 4
    if hash == keccak_packed("WETH") {
        let colors = colors1(variant)
        join((rects1(colors).as_bytes(), polygons1(colors).as_bytes(), circles1(colors).as_bytes()))
    } else if hash == keccak_packed("wstETH") {
        let colors = colors2(variant)
        join((rects2(colors).as_bytes(), circles2(colors).as_bytes()))
    } else {
        let colors = colors3(variant)
        join((rects3(colors).as_bytes(), circles3(colors).as_bytes()))
    }
}''')
for value,name in literals.items():
    b=value.encode();out.append(f'fn {name}() -> DynString uses (mem: mut RawMem) {{')
    out.append(f'    let data = core::ptr::alloc_bytes({(len(b)+31)//32*32})')
    for i in range(0,len(b),32):out.append(f'    mem.mstore(addr: core::ptr::offset_bytes(data, {i}), value: 0x{b[i:i+32].ljust(32,bytes([0])).hex()})')
    out.append(f'    DynString::from_payload(source: core::ptr::MemSpan::from_raw_parts(ptr: data, len: {len(b)}))\n}}')
(ROOT/'src/metadata_bauhaus.fe').write_text(normalize_joins(re.sub(r'^(pub )?fn ', lambda m: '#[inline(never)]\n'+m[0], '\n'.join(out)+'\n', flags=re.M)))
print(f'Generated {len(functions)} geometry functions and {len(literals)} exact literal segments')
